export const messages: Record<Locale, Record<MessageKey, string>> = { en, et };

export function normalizeLocale(value: string | undefined | null): Locale {
  return (LOCALES as readonly string[]).includes(value ?? "") ? (value as Locale) : "en";
}

export function translator(locale: Locale) {
  return (key: MessageKey): string => messages[locale][key];
}

/** Replaces {name} placeholders in a message template. */
export function fill(template: string, vars: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => vars[key] ?? "");
}

/** Message by plain string key (for keys built at runtime); falls back to the key itself. */
export function msg(locale: Locale, key: string): string {
  return (messages[locale] as Record<string, string>)[key] ?? key;
}

